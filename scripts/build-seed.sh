#!/bin/bash
# Build combined seed.sql from base + all course SQL files
#
# scripts/sql/ holds two kinds of file:
#   * course seed data — a self-contained script that inserts one course plus
#     its tees and holes (emitted by the course-ingest generator).
#   * operator helper queries and runbook templates — hand-run diagnostics such
#     as compare_courses.sql and merge_courses_template.sql. They carry psql
#     `:variables` and <PLACEHOLDER> tokens, so they are not valid standalone
#     SQL; concatenating them aborts `supabase db reset` part-way through the
#     seed and leaves the developer with no course data.
#
# Only the first kind belongs in seed.sql, so files are included on evidence
# rather than on the glob: a file ships only if it actually inserts a course.
# Anything else in the directory is skipped and listed at the end of the run.

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"

SEED_BASE="$PROJECT_ROOT/supabase/seed-base.sql"
SEED_OUTPUT="$PROJECT_ROOT/supabase/seed.sql"
COURSES_DIR="$PROJECT_ROOT/scripts/sql"

# A course seed file inserts into public.course; helper queries and templates
# only read from it (or patch other tables), so they never match.
is_course_seed() {
  grep -qiE '^[[:space:]]*insert into public\.course[[:space:]]*\(' "$1"
}

echo "Building seed.sql..."

# Start with the base seed file
cat "$SEED_BASE" > "$SEED_OUTPUT"

# Add a separator comment
echo "" >> "$SEED_OUTPUT"
echo "-- ============================================" >> "$SEED_OUTPUT"
echo "-- Additional course data from scripts/sql/" >> "$SEED_OUTPUT"
echo "-- Generated by scripts/build-seed.sh" >> "$SEED_OUTPUT"
echo "-- ============================================" >> "$SEED_OUTPUT"

# Append the course seed files from scripts/sql/
file_count=0
skipped=()
for sql_file in "$COURSES_DIR"/*.sql; do
  if [ -f "$sql_file" ]; then
    filename=$(basename "$sql_file")
    if ! is_course_seed "$sql_file"; then
      skipped+=("$filename")
      continue
    fi
    echo "" >> "$SEED_OUTPUT"
    echo "-- Source: scripts/sql/$filename" >> "$SEED_OUTPUT"
    cat "$sql_file" >> "$SEED_OUTPUT"
    ((++file_count))
  fi
done

echo "✓ Combined seed-base.sql + $file_count course files into seed.sql"

if [ ${#skipped[@]} -gt 0 ]; then
  echo "  Skipped ${#skipped[@]} non-course file(s) in scripts/sql/ (operator tooling, not seed data):"
  for filename in "${skipped[@]}"; do
    echo "    - $filename"
  done
fi
